H = re.compile(r"^(#{1,3}) (.+?)\s*$")
PART = re.compile(r"^PART ([A-Z])\.")
NUM = re.compile(r"^((?:B-)?\d+(?:-\d+)?)\.\s*(.*)$")


def pick(ovr, part, key):
    """PART 를 앞에 붙인 키 → 그냥 키 → 부모 절 순으로 찾는다."""
    parent = key.split("-")[0] if not key.startswith("B-") else "B"
    for k in (f"{part}:{key}", key, f"{part}:{parent}", parent, part, f"PART {part}"):
        if k in ovr:
            return ovr[k]
    return DEFAULT


def build():
    rows = []
    for tag, fn in FILES:
        ovr = OVR[tag]
        part = ""
        with open(os.path.join(BOOK, fn), encoding="utf-8") as fh:
            lines = fh.read().splitlines()
        incode = False
        first = True
        for ln in lines:
            if ln.startswith("```"):
                incode = not incode
            if incode:
                continue
            m = H.match(ln)
            if not m:
                continue
            lv, title = len(m.group(1)), m.group(2)
            if lv == 1:
                pm = PART.match(title)
                if pm:
                    part = pm.group(1)
                    st, where = ovr.get("PART " + part, ovr.get(part, ("○", "PART 제목 — 아래 각 절의 판정을 본다")))
                    rows.append([tag, "PART " + part, title, st, "", where])
                elif first:
                    st, where = ovr.get("제목", DEFAULT)
                    rows.append([tag, "제목", title, st, "", where])
                first = False
                continue
            nm = NUM.match(title)
            if nm:
                key, rest = nm.group(1), nm.group(2)
                st, where = pick(ovr, part, key)
                rows.append([tag, key if lv == 2 else "  " + key, rest, st, f"PART {part}" if part else "", where])
            else:
                key = "원본 영상" if title.startswith("원본 영상") else ("읽는법" if "읽는 법" in title else title)
                st, where = ovr.get(key, DEFAULT)
                rows.append([tag, "" if lv == 2 else "  ", title, st, "", where])
    return rows


if __name__ == "__main__":
    rows = build()
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* gen_toc51.py 가 만든다 — 직접 고치지 않는다. [교재, 절, 제목, 판정, PART, 어디서 보나] */\n")
        fh.write("const TOC51=" + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n")
    from collections import Counter
    c = Counter(r[3] for r in rows)
    print(len(rows), dict(c))
