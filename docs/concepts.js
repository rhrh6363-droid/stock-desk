/* ── 작은 그림 ── 가격은 0(아래)~100(위) 눈금, x 는 0..n-1 */
const CUP="var(--up)", CDN="var(--down)", COK="var(--ok)", CBD="var(--bad)", CMD="var(--mid)", CNV="var(--navy)", CI2="var(--ink-2)", CI3="var(--ink-3)";
function FG(sp){
  const W=240,H=sp.H||128,hasV=!!sp.v,PT=12,PB=hasV?H-34:H-14,VB=H-4,VT=PB+8;
  const tw=t=>[...String(t)].reduce((w,ch)=>w+(/[ㄱ-힣]/.test(ch)?9:5.4),0);
  const RM=sp.rm??Math.min(96,Math.max(0,...(sp.lines||[]).filter(l=>l.t&&!l.left&&l.i2==null).map(l=>tw(l.t)+8),...(sp.paths||[]).filter(p=>p.t).map(p=>tw(p.t)+6)));
  const n=sp.n||(sp.c?sp.c.length:20), step=(W-20-RM)/n, X=i=>10+step*(i+.5), Y=p=>PB-(PB-PT)*p/100;
  const f=v=>v.toFixed(1);
  let g="";
  (sp.zones||[]).forEach(z=>{const x1=z.i1!=null?X(z.i1)-step/2:4, x2=z.i2!=null?X(z.i2)+step/2:W-4;
    g+=`<rect x="${f(x1)}" y="${f(Y(Math.max(z.a,z.b)))}" width="${f(x2-x1)}" height="${f(Math.abs(Y(z.a)-Y(z.b)))}" fill="${z.col||CNV}" opacity="${z.op||.13}"/>`
      +(z.t?`<text x="${f(x2-3)}" y="${f(Y(Math.max(z.a,z.b))+10)}" text-anchor="end" font-size="9" fill="${z.col||CNV}">${z.t}</text>`:"");});
  (sp.lines||[]).forEach(l=>{const x1=l.i1!=null?X(l.i1):6, x2=l.i2!=null?X(l.i2):W-6-RM, tx=l.left?x1+2:l.i2!=null?x2-2:W-RM-2;
    g+=`<line x1="${f(x1)}" x2="${f(x2)}" y1="${f(Y(l.p))}" y2="${f(Y(l.p))}" stroke="${l.col||CI3}" stroke-width="${l.w||1.1}" ${l.d===false?"":`stroke-dasharray="${l.d||"4 3"}"`}/>`
      +(l.t?`<text x="${f(RM&&!l.left&&l.i2==null?tx+4:tx)}" y="${f(Y(l.p)+(RM&&!l.left&&l.i2==null?3:l.below?10:-3))}" text-anchor="${l.left||(RM&&l.i2==null)?"start":"end"}" font-size="9" fill="${l.col||CI3}">${l.t}</text>`:"");});
  (sp.paths||[]).forEach(p=>{const pts=p.p.map(([i,y])=>`${f(X(i))},${f(Y(y))}`).join(" ");
    g+=`<polyline points="${pts}" fill="none" stroke="${p.col||CI2}" stroke-width="${p.w||1.6}" stroke-linejoin="round" ${p.d?`stroke-dasharray="${p.d}"`:""}/>`
      +(p.t?`<text x="${f(X(p.p[p.p.length-1][0])+3)}" y="${f(Y(p.p[p.p.length-1][1])+3)}" font-size="9" fill="${p.col||CI2}">${p.t}</text>`:"");});
  (sp.c||[]).forEach((k,i)=>{if(!k) return; const [o,h,l,c]=k, col=c>=o?CUP:CDN, x=X(i), bw=Math.max(2,step*.62);
    g+=`<line x1="${f(x)}" x2="${f(x)}" y1="${f(Y(h))}" y2="${f(Y(l))}" stroke="${col}" stroke-width="1"/>`
      +`<rect x="${f(x-bw/2)}" y="${f(Y(Math.max(o,c)))}" width="${f(bw)}" height="${f(Math.max(1.2,Math.abs(Y(o)-Y(c))))}" fill="${col}"/>`;});
  if(hasV){const mx=Math.max(...sp.v.map(Math.abs));
    sp.v.forEach((v,i)=>{if(v==null) return; const hh=(VB-VT)*Math.abs(v)/mx, col=sp.vc?sp.vc[i]:(sp.c&&sp.c[i]?(sp.c[i][3]>=sp.c[i][0]?CUP:CDN):CI3);
      g+=`<rect x="${f(X(i)-Math.max(2,step*.62)/2)}" y="${f(VB-hh)}" width="${f(Math.max(2,step*.62))}" height="${f(Math.max(.8,hh))}" fill="${col}" opacity=".55"/>`;});
    g+=`<text x="4" y="${VT+6}" font-size="8.5" fill="${CI3}">거래량</text>`;}
  (sp.marks||[]).forEach(m=>{const x=X(m.i), y=Y(m.p);
    g+=(m.dot===false?"":`<circle cx="${f(x)}" cy="${f(y)}" r="2.6" fill="${m.col||CNV}"/>`)
      +`<text x="${f(x+(m.dx||0))}" y="${f(y+(m.below?12:-6))}" text-anchor="${m.a||"middle"}" font-size="9.5" font-weight="700" fill="${m.col||CNV}">${m.t}</text>`;});
  (sp.notes||[]).forEach(t=>g+=`<text x="${t.x}" y="${t.y}" font-size="${t.s||9}" text-anchor="${t.a||"start"}" fill="${t.col||CI2}" ${t.b?'font-weight="700"':""}>${t.t}</text>`);
  return `<svg class="fig" viewBox="0 0 ${W} ${H}" role="img">${g}</svg>`;
}
