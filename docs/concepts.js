let TERMRX=null, TERMMAP=null;
function termIndex(){
  if(TERMRX) return;
  TERMMAP={}; const all=[];
  Object.entries(GLOSS).forEach(([id,g])=>(g.al||[]).forEach(a=>{ if(!TERMMAP[a]){TERMMAP[a]=id; all.push(a);} }));
  all.sort((a,b)=>b.length-a.length);
  TERMRX=new RegExp(all.map(a=>a.replace(/[.*+?^${}()|[\]\\]/g,"\\$&")).join("|"),"g");
}
function termify(root){
  if(!root||typeof document.createTreeWalker!=="function") return;
  termIndex();
  root.querySelectorAll(".card").forEach(card=>{
    const seen=new Set();
    const tw=document.createTreeWalker(card,NodeFilter.SHOW_TEXT,{acceptNode:n=>{
      const p=n.parentElement; if(!p) return NodeFilter.FILTER_REJECT;
      if(p.closest("svg,button,a,h2,summary,.term,.legend,.lytog,.cguide,.howto,.t,.src,.ref,th,input,label,.tip")) return NodeFilter.FILTER_REJECT;
      return /\S/.test(n.nodeValue)?NodeFilter.FILTER_ACCEPT:NodeFilter.FILTER_REJECT;}});
    const nodes=[]; while(tw.nextNode()) nodes.push(tw.currentNode);
    nodes.forEach(node=>{
      const txt=node.nodeValue; TERMRX.lastIndex=0; let m, last=0, frag=null;
      while((m=TERMRX.exec(txt))){
        const id=TERMMAP[m[0]]; if(seen.has(id)) continue;
        seen.add(id); frag=frag||document.createDocumentFragment();
        frag.appendChild(document.createTextNode(txt.slice(last,m.index)));
        const b=document.createElement("span"); b.className="term"; b.dataset.g=id; b.tabIndex=0; b.textContent=m[0];
        frag.appendChild(b); last=m.index+m[0].length;
      }
      if(frag){frag.appendChild(document.createTextNode(txt.slice(last))); node.parentNode.replaceChild(frag,node);}
    });
  });
}

